#!/usr/bin/env bash
# Build the IRIX 7 release artefacts.
#
# This script is intentionally strict: until M0 (toolchain) is complete it
# fails with a clear message rather than producing a fake release.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

VERSION="${GITHUB_REF_NAME:-$(git describe --tags --always --dirty 2>/dev/null || echo dev)}"
DIST="$ROOT/dist"

rm -rf "$DIST"
mkdir -p "$DIST"

if [ ! -f Cargo.toml ]; then
  echo "No Rust workspace at the repository root." >&2
  echo "M0 (toolchain unblocked) is not complete; a release cannot be built." >&2
  exit 1
fi

echo "Building IRIX 7 $VERSION"

# Kernel and ROM share the n32 target. The ROM additionally links against its
# PROM/DRAM linker script.
cargo build --release -Z build-std=core,alloc \
  --target targets/mips3-sgi-irix7-n32.json -p kernel
CARGO_TARGET_MIPS3_SGI_IRIX7_N32_RUSTFLAGS="-Clink-arg=-Trom/linker.ld" \
  cargo build --release -Z build-std=core,alloc \
  --target targets/mips3-sgi-irix7-n32.json --features cross -p rom

# Copy the artefacts when the workspace defines these binaries. The names are
# part of the release contract; adjust the workspace before the first release.
for artifact in irix7-kernel irix7-rom irix7-boot.bundle; do
  for profile in release; do
    for target in mips3-sgi-irix7-n32; do
      src="target/$target/$profile/$artifact"
      if [ -f "$src" ]; then
        cp "$src" "$DIST/"
      fi
    done
  done
done

# Read-only root image, if a root tree is present.
if [ -d root ] && command -v mkfs.erofs >/dev/null 2>&1; then
  mkfs.erofs -T -U clear "$DIST/irix7-root.erofs" root
elif [ -d root ]; then
  echo "root/ exists but mkfs.erofs is not installed; skipping the root image." >&2
fi

# Manifest.
cat > "$DIST/manifest.json" <<EOF
{
  "name": "IRIX 7",
  "version": "$VERSION",
  "kernel_abi": "n32",
  "rom_abi": "o32",
  "created": "$(date -u +%Y-%m-%dT%H:%M:%SZ)",
  "commit": "$(git rev-parse HEAD 2>/dev/null || echo unknown)"
}
EOF

# SBOM is generated by CI; if syft is available locally, generate it here.
if command -v syft >/dev/null 2>&1; then
  syft dir:. -o spdx-json > "$DIST/irix7.spdx.json"
fi

echo
echo "Artefacts in $DIST:"
ls -lh "$DIST"
