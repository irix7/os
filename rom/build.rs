// Build script for the ROM.
//
// Extracts the kernel image from its ELF file as a flat binary (all PT_LOAD
// segments laid out at their physical addresses), then writes it out as
// `src/boot/payload.S` so `main.rs` can pull it into the PROM image with
// `global_asm!`.
//
// The kernel must already be built before the ROM:
//   cargo build --release --target targets/mips3-sgi-irix7-n32.json -p kernel

use std::env;
use std::fs;
use std::path::PathBuf;

fn be32(b: &[u8], off: usize) -> u32 {
    u32::from_be_bytes([b[off], b[off + 1], b[off + 2], b[off + 3]])
}

fn be16(b: &[u8], off: usize) -> u16 {
    u16::from_be_bytes([b[off], b[off + 1]])
}

/// Extract the flat load image (all PT_LOAD segments, keyed by physical address).
fn elf_to_flat(elf: &[u8]) -> Option<Vec<u8>> {
    if elf.len() < 52 || &elf[0..4] != b"\x7FELF" {
        return None;
    }
    // ELF32 big-endian
    if elf[4] != 1 || elf[5] != 2 {
        return None;
    }
    let phoff = be32(elf, 0x1C) as usize;
    let phentsize = be16(elf, 0x2A) as usize;
    let phnum = be16(elf, 0x2C) as usize;
    if phentsize < 32 || phnum == 0 {
        return None;
    }

    struct Seg {
        offset: usize,
        paddr: u32,
        filesz: usize,
    }
    let mut segs: Vec<Seg> = Vec::new();

    for i in 0..phnum {
        let base = phoff + i * phentsize;
        if base + 32 > elf.len() {
            return None;
        }
        let p_type = be32(elf, base);
        if p_type != 1 {
            continue; // PT_LOAD only
        }
        let offset = be32(elf, base + 4) as usize;
        let paddr = be32(elf, base + 12);
        let filesz = be32(elf, base + 16) as usize;
        if filesz == 0 {
            continue;
        }
        if offset.checked_add(filesz)? > elf.len() {
            return None;
        }
        segs.push(Seg { offset, paddr, filesz });
    }

    if segs.is_empty() {
        return None;
    }
    segs.sort_by_key(|s| s.paddr);

    let base = segs[0].paddr;
    let end = segs.iter().map(|s| s.paddr + s.filesz as u32).max()?;
    let size = (end - base) as usize;
    let mut flat = vec![0u8; size];
    for s in &segs {
        let dst = (s.paddr - base) as usize;
        flat[dst..dst + s.filesz].copy_from_slice(&elf[s.offset..s.offset + s.filesz]);
    }
    Some(flat)
}

fn emit_payload_asm(payload: &[u8], path: &PathBuf) {
    let mut asm = String::new();
    asm.push_str("/* generated by rom/build.rs - do not edit */\n");
    asm.push_str(".section .payload, \"a\", @progbits\n");
    asm.push_str(".align 4\n");
    asm.push_str(".globl rom_payload_start\n");
    asm.push_str("rom_payload_start:\n");
    for chunk in payload.chunks(4) {
        let mut w: u32 = 0;
        for (i, &b) in chunk.iter().enumerate() {
            w |= (b as u32) << (24 - i * 8);
        }
        asm.push_str(&format!("    .word 0x{:08X}\n", w));
    }
    asm.push_str(".globl rom_payload_end\n");
    asm.push_str("rom_payload_end:\n");
    fs::write(path, asm).expect("write payload.S");
}

fn main() {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let payload_s = manifest_dir.join("src/boot/payload.S");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=CARGO_TARGET_DIR");

    let target_dir = match env::var("CARGO_TARGET_DIR") {
        Ok(v) => PathBuf::from(v),
        Err(_) => manifest_dir
            .parent()
            .map(|p| p.join("target"))
            .unwrap_or_else(|| PathBuf::from("target")),
    };

    let target = env::var("TARGET").unwrap_or_default();
    let profile = env::var("PROFILE").unwrap_or_else(|_| "release".into());
    let kernel_elf = target_dir.join(&target).join(&profile).join("kernel");

    println!("cargo:rerun-if-changed={}", kernel_elf.display());

    let payload = match fs::read(&kernel_elf).ok().and_then(|data| elf_to_flat(&data)) {
        Some(p) => p,
        None => {
            println!(
                "cargo:warning=kernel image not found or unreadable at {}; embedding empty payload",
                kernel_elf.display()
            );
            Vec::new()
        }
    };

    emit_payload_asm(&payload, &payload_s);
    println!("cargo:warning=embedded kernel payload: {} bytes", payload.len());
}
